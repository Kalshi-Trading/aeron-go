// TestChannelUriGoldenJava compares ParseChannelUri and NewChannelUriStringBuilderFromString against
// testdata/channeluri_golden.txt, generated by Java 1.53.3 ChannelUri / ChannelUriStringBuilder
// (testdata/ChannelUriGolden.java).
func TestChannelUriGoldenJava(t *testing.T) {
	f, err := os.Open("testdata/channeluri_golden.txt")
	require.NoError(t, err)
	defer f.Close()

	scanner := bufio.NewScanner(f)
	cases := 0
	for scanner.Scan() {
		in := strings.TrimPrefix(scanner.Text(), "IN\t")
		require.True(t, scanner.Scan())
		wantParse := strings.TrimPrefix(scanner.Text(), "PARSE\t")
		require.True(t, scanner.Scan())
		wantBuild := strings.TrimPrefix(scanner.Text(), "BUILD\t")
		cases++

		assert.Equal(t, wantParse, goldenParse(in), "parse %q", in)
		assert.Equal(t, wantBuild, goldenBuild(in), "builder %q", in)
	}
	require.NoError(t, scanner.Err())
	require.Greater(t, cases, 100)
}

func goldenParse(s string) string {
	uri, err := ParseChannelUri(s)
	if err != nil {
		return "ERR"
	}
	tag := func(i int) string {
		if tags := uri.tags(); len(tags) > i {
			return tags[i]
		}
		return "null"
	}
	fields := []string{uri.Prefix(), uri.Media(), tag(0), tag(1)}
	var keys []string
	uri.ForEachParameter(func(k, _ string) { keys = append(keys, k) })
	sort.Strings(keys)
	for _, k := range keys {
		fields = append(fields, k+"="+uri.Get(k))
	}
	return strings.Join(fields, "\t")
}

func goldenBuild(s string) string {
	b, err := NewChannelUriStringBuilderFromString(s)
	if err != nil {
		return "ERR"
	}
	built, err := b.Build()
	if err != nil {
		return "ERR"
	}
	return built
}
